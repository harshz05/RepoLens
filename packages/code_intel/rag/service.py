import os
import json
import httpx
from typing import Optional, Dict, Any, List
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, desc

from packages.db.models import (
    Repository,
    RepositoryVersion,
    ChatSession,
    ChatMessage,
    Citation,
)
from packages.code_intel.retrieval.hybrid_engine import HybridRetrievalEngine
from packages.code_intel.rag.prompt_builder import PromptBuilder
from packages.code_intel.rag.citation_validator import CitationValidator
from packages.code_intel.models import RankedChunk, CitationRecord

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "").strip()
GEMINI_CHAT_MODEL = os.getenv("GEMINI_CHAT_MODEL", "gemini-1.5-pro")

class CodebaseRAGService:
    """
    End-to-End Grounded Codebase RAG and Conversational Assistant Service.
    Orchestrates Hybrid Retrieval, Prompt XML Fencing, LLM Generation, and Citation Validation.
    """

    @classmethod
    async def chat(
        cls,
        session: AsyncSession,
        repository_id: str,
        message: str,
        chat_session_id: Optional[str] = None,
        user_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        # 1. Fetch repository & latest completed version
        repo_stmt = select(Repository).where(Repository.id == repository_id)
        repo_res = await session.execute(repo_stmt)
        repo = repo_res.scalar_one_or_none()
        if not repo:
            raise ValueError("Repository not found")

        ver_stmt = (
            select(RepositoryVersion)
            .where(RepositoryVersion.repository_id == repository_id)
            .order_by(desc(RepositoryVersion.processed_at))
        )
        ver_res = await session.execute(ver_stmt)
        latest_ver = ver_res.scalars().first()
        if not latest_ver:
            raise ValueError("No analyzed version found for this repository")

        # 2. Execute Hybrid Retrieval
        retrieval_res = await HybridRetrievalEngine.retrieve(
            session=session,
            repository_version_id=latest_ver.id,
            query=message,
            mode="hybrid",
            limit=6,
            expand_graph_context=True,
        )

        # 3. Assemble Grounded Prompt
        system_instruction = PromptBuilder.build_system_instruction()
        user_prompt = PromptBuilder.build_user_prompt(message, retrieval_res.chunks)

        # 4. Generate Answer via Gemini or Deterministic Synthesis
        answer_text = await cls._generate_llm_response(
            system_instruction=system_instruction,
            user_prompt=user_prompt,
            query=message,
            chunks=retrieval_res.chunks,
        )

        # 5. Extract & Validate Citations against AST Database
        verified_citations = await CitationValidator.extract_and_validate(
            session=session,
            repository_version_id=latest_ver.id,
            response_text=answer_text,
        )

        # If no citations were generated by LLM, synthesize citations from top retrieved chunks
        if not verified_citations and retrieval_res.chunks:
            for c in retrieval_res.chunks[:3]:
                verified_citations.append(
                    CitationRecord(
                        file_path=c.file_path,
                        start_line=c.start_line,
                        end_line=c.end_line,
                        snippet=f"{c.file_path} (lines {c.start_line}-{c.end_line})",
                        confidence_score=c.score,
                        symbol_name=c.symbol_fqn,
                        file_id=c.file_id,
                        symbol_id=c.symbol_id,
                    )
                )

        # 6. Manage ChatSession
        chat_sess = None
        if chat_session_id:
            sess_stmt = select(ChatSession).where(ChatSession.id == chat_session_id)
            sess_res = await session.execute(sess_stmt)
            chat_sess = sess_res.scalar_one_or_none()

        if not chat_sess:
            first_words = message.strip().split()[:6]
            title = " ".join(first_words) if first_words else "Architectural Chat"
            chat_sess = ChatSession(
                repository_id=repo.id,
                user_id=user_id,
                title=title[:250],
            )
            session.add(chat_sess)
            await session.flush()

        # 7. Persist User & Assistant Messages
        user_msg = ChatMessage(
            chat_session_id=chat_sess.id,
            role="user",
            content=message,
        )
        session.add(user_msg)

        serialized_chunks = [
            {
                "chunk_id": c.chunk_id,
                "file_path": c.file_path,
                "symbol_fqn": c.symbol_fqn,
                "start_line": c.start_line,
                "end_line": c.end_line,
                "score": c.score,
                "match_type": c.match_type,
            }
            for c in retrieval_res.chunks
        ]

        assistant_msg = ChatMessage(
            chat_session_id=chat_sess.id,
            role="assistant",
            content=answer_text,
            retrieved_context_json=json.dumps(serialized_chunks),
        )
        session.add(assistant_msg)
        await session.flush()

        # 8. Persist Citations
        saved_citations_data = []
        for cit in verified_citations:
            cit_rec = Citation(
                message_id=assistant_msg.id,
                file_id=cit.file_id,
                symbol_id=cit.symbol_id,
                file_path=cit.file_path,
                start_line=cit.start_line,
                end_line=cit.end_line,
                text_snippet=cit.snippet,
                confidence_score=cit.confidence_score,
            )
            session.add(cit_rec)
            saved_citations_data.append({
                "file_path": cit.file_path,
                "start_line": cit.start_line,
                "end_line": cit.end_line,
                "symbol_name": cit.symbol_name,
                "snippet": cit.snippet,
                "confidence_score": cit.confidence_score,
            })

        await session.commit()

        return {
            "session_id": chat_sess.id,
            "message_id": assistant_msg.id,
            "response": answer_text,
            "citations": saved_citations_data,
            "retrieved_chunks": [
                {
                    "chunk_id": c.chunk_id,
                    "file_path": c.file_path,
                    "symbol_fqn": c.symbol_fqn,
                    "kind": c.symbol_kind,
                    "start_line": c.start_line,
                    "end_line": c.end_line,
                    "content": c.content,
                    "score": c.score,
                    "match_type": c.match_type,
                    "graph_context": {
                        "symbol_fqn": c.graph_context.symbol_fqn,
                        "kind": c.graph_context.kind,
                        "callers": c.graph_context.callers,
                        "callees": c.graph_context.callees,
                    } if c.graph_context else None,
                }
                for c in retrieval_res.chunks
            ],
        }

    @classmethod
    async def _generate_llm_response(
        cls,
        system_instruction: str,
        user_prompt: str,
        query: str,
        chunks: List[RankedChunk],
    ) -> str:
        api_key = os.getenv("GEMINI_API_KEY", "").strip()

        if api_key:
            try:
                url = f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_CHAT_MODEL}:generateContent?key={api_key}"
                payload = {
                    "systemInstruction": {
                        "parts": [{"text": system_instruction}]
                    },
                    "contents": [
                        {
                            "role": "user",
                            "parts": [{"text": user_prompt}]
                        }
                    ],
                    "generationConfig": {
                        "temperature": 0.2,
                        "maxOutputTokens": 2048,
                    }
                }
                async with httpx.AsyncClient(timeout=45.0) as client:
                    resp = await client.post(url, json=payload)
                    if resp.status_code == 200:
                        data = resp.json()
                        candidates = data.get("candidates", [])
                        if candidates:
                            parts = candidates[0].get("content", {}).get("parts", [])
                            if parts:
                                return parts[0].get("text", "")
            except Exception:
                pass

        # Deterministic Grounded Synthesis (used when GEMINI_API_KEY is not set or during offline testing)
        if not chunks:
            return "I cannot find evidence for this in the analyzed repository."

        top_chunk = chunks[0]
        sym_name = top_chunk.symbol_fqn or top_chunk.file_path
        lines_str = f"[{top_chunk.file_path}:{top_chunk.start_line}-{top_chunk.end_line}]"

        explanation_parts = [
            f"Based on the analyzed codebase, `{sym_name}` is defined in {lines_str}.",
        ]

        if top_chunk.graph_context:
            if top_chunk.graph_context.callers:
                callers_text = ", ".join(f"`{c}`" for c in top_chunk.graph_context.callers)
                explanation_parts.append(f"It is invoked upstream by: {callers_text}.")
            if top_chunk.graph_context.callees:
                callees_text = ", ".join(f"`{c}`" for c in top_chunk.graph_context.callees)
                explanation_parts.append(f"Downstream, it depends on: {callees_text}.")

        # Add secondary citations from subsequent chunks
        for secondary in chunks[1:3]:
            sec_lines = f"[{secondary.file_path}:{secondary.start_line}-{secondary.end_line}]"
            sec_sym = secondary.symbol_fqn or secondary.file_path
            explanation_parts.append(f"Related logic for `{sec_sym}` is implemented in {sec_lines}.")

        return " ".join(explanation_parts)
